import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { fetchUiBundle, findLatestUiPort } from "../src/lib/runtime-bundle.mjs";
import { createLocalizedBundle, loadDomTranslations } from "../src/lib/translator.mjs";
import { sha256Buffer } from "../src/lib/hash.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const expectedSourceHash = "5EF4FD67A1D4FAC0B41271B08AF70B4A028AB0A700E3BF86CB07544940A4F7E5";
const outputPath = process.argv[2] ?? path.join(projectRoot, ".runtime", "build", "2.15.0", "agy_zhcn_ui_main.js");
const port = await findLatestUiPort();
if (!port) throw new Error("Antigravity UI is not running; cannot acquire the v2.15.0 UI bundle.");
const source = await fetchUiBundle(port);
if (sha256Buffer(source) !== expectedSourceHash) throw new Error("Runtime UI fingerprint mismatch.");
const dictionary = await loadDomTranslations();
const localized = createLocalizedBundle(source, dictionary);
if (localized.coverage.hits === 0) throw new Error("Translation dictionary has no matches in the runtime UI.");
await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, localized.buffer);
console.log(`Source SHA256: ${expectedSourceHash}`);
console.log(`Localized SHA256: ${localized.sha256}`);
console.log(`Dictionary coverage: ${localized.coverage.hits}/${localized.coverage.total}`);
console.log(`Output: ${path.resolve(outputPath)}`);
